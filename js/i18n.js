export function detectLang() {
  const saved = localStorage.getItem("glimmer-grove-lang");
  if (saved === "en" || saved === "es") return saved;
  return (navigator.language || "en").toLowerCase().startsWith("es") ? "es" : "en";
}

export function comboLabel(combo, lang) {
  const t = STR[lang] || STR.en;
  if (combo >= 5) return t.aurora;
  if (combo === 4) return t.divine;
  if (combo === 3) return t.sweet;
  if (combo === 2) return t.nice;
  return "";
}
